"""Builds a commit leaderboard of the user's public repos and injects it into README.md."""
import os
import re
import requests

USER = os.environ.get("GH_USER", "sadiqur199")
TOKEN = os.environ.get("GITHUB_TOKEN")
API = "https://api.github.com"
HEADERS = {"Accept": "application/vnd.github+json"}
if TOKEN:
    HEADERS["Authorization"] = f"Bearer {TOKEN}"

START, END = "<!--LEADERBOARD:START-->", "<!--LEADERBOARD:END-->"
TOP_N = 10
MEDALS = ["🥇", "🥈", "🥉"]


def get_repos():
    repos, page = [], 1
    while True:
        r = requests.get(f"{API}/users/{USER}/repos", headers=HEADERS,
                         params={"per_page": 100, "page": page, "type": "owner"}, timeout=30)
        r.raise_for_status()
        data = r.json()
        if not data:
            break
        repos.extend(data)
        page += 1
    return [x for x in repos if not x["fork"]]


def commit_count(full_name):
    r = requests.get(f"{API}/repos/{full_name}/commits", headers=HEADERS,
                     params={"author": USER, "per_page": 1}, timeout=30)
    if r.status_code != 200:  # e.g. 409 for empty repos
        return 0
    link = r.headers.get("Link", "")
    m = re.search(r'[?&]page=(\d+)>; rel="last"', link)
    return int(m.group(1)) if m else len(r.json())


def bar(value, maximum, width=15):
    filled = round(width * value / maximum) if maximum else 0
    return "█" * filled + "░" * (width - filled)


def build_table(rows):
    if not rows:
        return "*No commits found yet.*"
    maximum = rows[0][1]
    total = sum(c for _, c, *_ in rows)
    lines = ["| Rank | Repository | Commits | Progress | ⭐ | Language |",
             "|:---:|---|:---:|---|:---:|---|"]
    for i, (repo, commits, stars, lang) in enumerate(rows, 1):
        rank = MEDALS[i - 1] if i <= 3 else f"#{i}"
        lines.append(f"| {rank} | [{repo}](https://github.com/{USER}/{repo}) | **{commits}** | "
                     f"`{bar(commits, maximum)}` | {stars} | {lang or '-'} |")
    lines.append("")
    lines.append(f"<sub>Total commits across top {len(rows)} repos: **{total}** · auto-generated by GitHub Actions</sub>")
    return "\n".join(lines)


def main():
    rows = []
    for repo in get_repos():
        c = commit_count(repo["full_name"])
        if c > 0:
            rows.append((repo["name"], c, repo["stargazers_count"], repo["language"]))
    rows.sort(key=lambda x: x[1], reverse=True)
    table = build_table(rows[:TOP_N])

    with open("README.md", encoding="utf-8") as f:
        content = f.read()
    pattern = re.compile(f"{re.escape(START)}.*?{re.escape(END)}", re.DOTALL)
    new = pattern.sub(f"{START}\n{table}\n{END}", content)
    with open("README.md", "w", encoding="utf-8") as f:
        f.write(new)


if __name__ == "__main__":
    main()
